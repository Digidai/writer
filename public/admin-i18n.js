export function makeAdminT(lang) {
  const table = ADMIN_MESSAGES[lang] || ADMIN_MESSAGES.en;
  return function t(key, vars) {
    let s = table[key] ?? ADMIN_MESSAGES.en[key] ?? key;
    if (vars) {
      for (const [name, value] of Object.entries(vars)) s = s.replaceAll(`{${name}}`, String(value));
    }
    return s;
  };
}
